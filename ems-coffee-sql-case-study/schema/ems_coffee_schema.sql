CREATE TABLE customers (
  customer_id INTEGER PRIMARY KEY,
  membership_start_date DATE,
  membership_end_date DATE
);

CREATE TABLE menu (
  menu_id VARCHAR(3) PRIMARY KEY,
  coffee_name VARCHAR(100),
  price DECIMAL(10,2)
);

