  order_id INTEGER,
  customer_id INTEGER REFERENCES customers(customer_id),
  order_date DATE,
  menu_id VARCHAR(3) REFERENCES menu(menu_id),
  quantity INTEGER,
  PRIMARY KEY (order_id, menu_id)
);

